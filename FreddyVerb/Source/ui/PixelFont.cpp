const uint8_t* PixelFont::glyph (juce::juce_wchar c) noexcept
{
    if (c < 32 || c > 126) c = '?';
    return kFont5x7[c - 32];
}

float PixelFont::drawText (juce::Graphics& g, const juce::String& text, float x, float y, float px,
                           juce::Colour on, juce::Colour off, DotShape shape, float dotFill)
{
    const float dot = px * dotFill;
    const float inset = (px - dot) * 0.5f;
    juce::Path onPath, offPath;
    const bool drawOff = ! off.isTransparent();
    float cx = x;
    for (auto ch : text)
    {
        if (ch == 0x221e) ch = '~'; // infinity -> tilde glyph slot
        const auto* gl = glyph (ch);
        for (int col = 0; col < 5; ++col)
            for (int row = 0; row < 7; ++row)
            {
                const bool lit = (gl[col] >> row) & 1;
                if (! lit && ! drawOff) continue;
                juce::Rectangle<float> r (cx + (float) col * px + inset, y + (float) row * px + inset, dot, dot);
                auto& p = lit ? onPath : offPath;
                if (shape == DotShape::round) p.addEllipse (r);
                else p.addRectangle (r);
            }
        cx += 6.0f * px;
    }
    if (drawOff) { g.setColour (off); g.fillPath (offPath); }
    g.setColour (on);
    g.fillPath (onPath);
    return cx - x;
}

void PixelFont::drawFitted (juce::Graphics& g, const juce::String& text, juce::Rectangle<float> box,
                            juce::Justification just, juce::Colour on, juce::Colour off, DotShape shape, float maxPixel)
{
    if (text.isEmpty()) return;
    float px = std::min (box.getHeight() / 7.0f, maxPixel);
    const float w = textWidth (text, px) - px;
    if (w > box.getWidth()) px *= box.getWidth() / w;
    px = std::max (0.6f, px);
    const float tw = textWidth (text, px) - px;
    const float th = 7.0f * px;
    float x = box.getX(), y = box.getCentreY() - th * 0.5f;
    if (just.testFlags (juce::Justification::horizontallyCentred)) x = box.getCentreX() - tw * 0.5f;
    else if (just.testFlags (juce::Justification::right)) x = box.getRight() - tw;
    if (just.testFlags (juce::Justification::top)) y = box.getY();
    else if (just.testFlags (juce::Justification::bottom)) y = box.getBottom() - th;
    drawText (g, text, x, y, px, on, off, shape);
}

void PixelFont::drawSevenSegment (juce::Graphics& g, const juce::String& text, juce::Rectangle<float> box,
                                  juce::Colour on, juce::Colour off, float slant)
{
    // count digit cells (dots attach to the previous digit)
    int cells = 0;
    for (auto ch : text) if (ch != '.') ++cells;
    if (cells == 0) return;
    const float h = box.getHeight();
    const float cw = std::min (box.getWidth() / (float) cells, h * 0.7f);
    const float t = std::max (1.0f, cw * 0.16f); // segment thickness
    float x = box.getRight() - cw * (float) cells; // right-aligned like real readouts

    auto seg = [&] (juce::Path& p, float x0, float y0, float x1, float y1)
    {
        // hexagonal segment between two points
        const bool horiz = std::abs (y1 - y0) < std::abs (x1 - x0);
        juce::Path s;
        const float ht = t * 0.5f;
        if (horiz)
        {
            s.startNewSubPath (x0, y0); s.lineTo (x0 + ht, y0 - ht); s.lineTo (x1 - ht, y1 - ht);
            s.lineTo (x1, y1); s.lineTo (x1 - ht, y1 + ht); s.lineTo (x0 + ht, y0 + ht);
        }
        else
        {
            s.startNewSubPath (x0, y0); s.lineTo (x0 + ht, y0 + ht); s.lineTo (x1 + ht, y1 - ht);
            s.lineTo (x1, y1); s.lineTo (x1 - ht, y1 - ht); s.lineTo (x0 - ht, y0 + ht);
        }
        s.closeSubPath();
        p.addPath (s);
    };

    juce::Path onP, offP;
    const auto shear = juce::AffineTransform::shear (-slant, 0.0f).translated (slant * (box.getY() + h), 0.0f);
    for (int i = 0; i < text.length(); ++i)
    {
        const auto ch = text[i];
        if (ch == '.') continue;
        const bool dot = i + 1 < text.length() && text[i + 1] == '.';
        const uint8_t s = segmentsFor (ch);
        // every cell reserves a gap on the right for its decimal point so the dot
        // never merges into the digit's right-hand segments at small sizes
        const float l = x + t, r = x + cw - t * 2.2f;
        const float tp = box.getY() + t * 0.6f, md = box.getCentreY(), bt = box.getBottom() - t * 0.6f;
        const float gap = t * 0.25f;
        struct S { float x0, y0, x1, y1; } segs[7] = {
            { l + gap, tp, r - gap, tp }, { r, tp + gap, r, md - gap }, { r, md + gap, r, bt - gap },
            { l + gap, bt, r - gap, bt }, { l, md + gap, l, bt - gap }, { l, tp + gap, l, md - gap },
            { l + gap, md, r - gap, md } };
        for (int b = 0; b < 7; ++b)
            seg ((s >> b) & 1 ? onP : offP, segs[b].x0, segs[b].y0, segs[b].x1, segs[b].y1);
        { const float dd = std::max (1.6f, t * 1.4f); (dot ? onP : offP).addEllipse (r + t * 0.8f, bt - dd * 0.5f, dd, dd); }
        x += cw;
    }
    if (! off.isTransparent()) { g.setColour (off); g.fillPath (offP, shear); }
    g.setColour (on);
    g.fillPath (onP, shear);
}
